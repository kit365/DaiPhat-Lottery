package com.daiphat.coreapi.infrastructure.adapter.out.lotteries.settlement.persistence;

import com.daiphat.coreapi.application.port.out.lotteries.SupplierSettlementAdjustmentRepositoryPort;
import com.daiphat.coreapi.domain.model.enums.lottery.SupplierSettlementAdjustmentGroupType;
import com.daiphat.coreapi.domain.model.lotteries.SupplierSettlementAdjustmentModel;
import com.daiphat.coreapi.infrastructure.persistence.entity.lotteries.SupplierSettlementAdjustmentEntity;
import com.daiphat.coreapi.infrastructure.persistence.entity.lotteries.SupplierSettlementEntity;
import com.daiphat.coreapi.infrastructure.persistence.repository.lotteries.SupplierSettlementAdjustmentRepository;
import lombok.RequiredArgsConstructor;
import org.springframework.stereotype.Component;

import java.math.BigDecimal;
import java.time.LocalDateTime;
import java.util.List;

@Component
@RequiredArgsConstructor
public class SupplierSettlementAdjustmentRepositoryAdapter implements SupplierSettlementAdjustmentRepositoryPort {

    private final SupplierSettlementAdjustmentRepository repository;

    @Override
    public SupplierSettlementAdjustmentModel save(SupplierSettlementAdjustmentModel model) {
        SupplierSettlementAdjustmentEntity entity = toEntity(model);
        return toDomain(repository.save(entity));
    }

    @Override
    public List<SupplierSettlementAdjustmentModel> findBySettlementId(Long settlementId) {
        return repository.findBySupplierSettlement_IdAndDeletedAtIsNull(settlementId).stream()
                .map(this::toDomain)
                .toList();
    }

    @Override
    public void deleteBySettlementIdAndGroupType(Long settlementId, SupplierSettlementAdjustmentGroupType groupType) {
        List<SupplierSettlementAdjustmentEntity> rows =
                repository.findBySupplierSettlement_IdAndDeletedAtIsNull(settlementId);
        LocalDateTime now = LocalDateTime.now();
        for (SupplierSettlementAdjustmentEntity row : rows) {
            if (row.getGroupType() == groupType) {
                row.setDeletedAt(now);
                repository.save(row);
            }
        }
    }

    @Override
    public BigDecimal sumValueOnlyAdjustmentsBySettlementId(Long settlementId) {
        BigDecimal sum = repository.sumValueOnlyAdjustmentsBySettlementId(settlementId);
        return sum != null ? sum : BigDecimal.ZERO;
    }

    private SupplierSettlementAdjustmentModel toDomain(SupplierSettlementAdjustmentEntity entity) {
        return SupplierSettlementAdjustmentModel.builder()
                .id(entity.getId())
                .supplierSettlementId(entity.getSupplierSettlement() != null
                        ? entity.getSupplierSettlement().getId()
                        : null)
                .lotteryTicketSerialId(entity.getLotteryTicketSerialId())
                .groupType(entity.getGroupType())
                .reasonCode(entity.getReasonCode())
                .amount(entity.getAmount())
                .customName(entity.getCustomName())
                .autoGenerated(entity.isAutoGenerated())
                .note(entity.getNote())
                .resolvedBy(entity.getResolvedBy())
                .createdAt(entity.getCreatedAt())
                .build();
    }

    private SupplierSettlementAdjustmentEntity toEntity(SupplierSettlementAdjustmentModel model) {
        SupplierSettlementEntity settlement = new SupplierSettlementEntity();
        settlement.setId(model.getSupplierSettlementId());
        return SupplierSettlementAdjustmentEntity.builder()
                .id(model.getId())
                .supplierSettlement(settlement)
                .lotteryTicketSerialId(model.getLotteryTicketSerialId())
                .groupType(model.getGroupType())
                .reasonCode(model.getReasonCode())
                .amount(model.getAmount())
                .customName(model.getCustomName())
                .autoGenerated(model.isAutoGenerated())
                .note(model.getNote())
                .resolvedBy(model.getResolvedBy())
                .build();
    }
}
